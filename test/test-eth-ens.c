#include <tap.h>
#include <ethc/ens.h>
#include <ethc/hex.h>
#include "test.h"
#include <assert.h>

void test_eth_ens_namehash(void) {
  uint8_t exp0[32] = {
    0xeb, 0x4f, 0x64, 0x7b, 0xea, 0x6c, 0xaa, 0x36,
    0x33, 0x3c, 0x81, 0x6d, 0x7b, 0x46, 0xfd, 0xcb,
    0x05, 0xf9, 0x46, 0x6e, 0xca, 0xcc, 0x14, 0x0e,
    0xa8, 0xc6, 0x6f, 0xaf, 0x15, 0xb3, 0xd9, 0xf1
  }, exp1[32] = {
    0x8f, 0xe9, 0xa5, 0x02, 0xdb, 0xe5, 0x77, 0x7c,
    0x49, 0x6c, 0x9d, 0x0d, 0xf2, 0xa2, 0xeb, 0xe3,
    0x30, 0xab, 0x3c, 0x0b, 0x79, 0xae, 0xf2, 0x68,
    0xcd, 0xbf, 0x17, 0x8a, 0x48, 0x38, 0x62, 0x41
  };

  uint8_t out0[32], out1[32];

  diag("eth_ens_namehash()");

  assert(eth_ens_namehash(out0, "test.eth") == ETH_OK);
  cmp_mem(out0, exp0, 32, "test.eth");

  assert(eth_ens_namehash(out1, "very.very.deep.name.ens") == ETH_OK);
  cmp_mem(out1, exp1, 32, "very.very.deep.name.ens");
}
